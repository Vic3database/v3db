export const eventGroupNames = Object.fromEntries(Object.entries(zhHans).map(([namespace, name]) => [namespace, {
  zhHans: name,
  en: english[namespace] || namespace.replaceAll("_", " ").replace(/\b\w/g, (letter) => letter.toUpperCase()),
}]));

export function eventGroupName(namespace, locale = "zh-Hans") {
  const entry = eventGroupNames[namespace];
  if (!entry) return namespace;
  return locale === "zh-Hans" ? entry.zhHans : entry.en;
}
